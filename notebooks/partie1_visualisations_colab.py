import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

"""On prépare les données (mes résultats dans sql)

- Répartion des clients pas pays
"""

data = {
    "country": ["USA", "France", "Germany", "Japan"],
    "nb_clients": [24, 12, 10, 8]
}

df = pd.DataFrame(data)
df

plt.figure(figsize=(12, 6))
sns.barplot(data=df, x="country", y="nb_clients", palette="viridis")
plt.title("Répartition des clients par pays")
plt.xlabel("Pays")
plt.ylabel("Nombre de clients")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

